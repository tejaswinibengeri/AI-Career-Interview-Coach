"""
Pydantic schemas for AI Mock Interview Sessions, Answers, Evaluations, and Performance Reports.
"""

from datetime import datetime
from pydantic import BaseModel, ConfigDict, Field


class CreateInterviewSessionRequest(BaseModel):
    """Request payload to initiate a new mock interview session."""

    role: str = Field("Software Engineer", description="Target job role (e.g. Frontend Engineer, Data Scientist)")
    difficulty: str = Field("Medium", description="Easy, Medium, Hard")
    total_questions: int = Field(3, ge=1, le=10, description="Total number of interview questions in session")


class SubmitAnswerRequest(BaseModel):
    """Request payload to submit a user answer for active interview question."""

    question_id: int
    user_answer: str = Field(..., min_length=2, description="Candidate text response")


class AIAnswerEvaluationPayload(BaseModel):
    """Schema to validate JSON output generated by Ollama for answer evaluation."""

    technical_correctness: float = Field(..., ge=0, le=100)
    relevance: float = Field(..., ge=0, le=100)
    completeness: float = Field(..., ge=0, le=100)
    communication: float = Field(..., ge=0, le=100)
    structure: float = Field(..., ge=0, le=100)
    clarity: float = Field(..., ge=0, le=100)
    overall_score: float = Field(..., ge=0, le=100)
    feedback: str = Field(..., description="Detailed constructive feedback")
    strengths: list[str] = Field(default_factory=list)
    improvements: list[str] = Field(default_factory=list)
    ideal_answer: str | None = Field(None, description="Sample ideal response snippet")


class InterviewEvaluationResponse(BaseModel):
    """Response schema for question evaluation."""

    model_config = ConfigDict(from_attributes=True)

    id: int
    answer_id: int
    technical_correctness: float
    relevance: float
    completeness: float
    communication: float
    structure: float
    clarity: float
    overall_score: float
    feedback: str
    strengths: list[str] = Field(default_factory=list)
    improvements: list[str] = Field(default_factory=list)
    ideal_answer: str | None = None
    evaluated_at: datetime


class InterviewQuestionResponse(BaseModel):
    """Response schema for interview question step."""

    model_config = ConfigDict(from_attributes=True)

    id: int
    question_text: str
    category: str
    difficulty: str
    question_order: int
    explanation: str | None = None
    user_answer: str | None = None
    evaluation: InterviewEvaluationResponse | None = None


class InterviewSessionResponse(BaseModel):
    """Response schema for active interview session state."""

    model_config = ConfigDict(from_attributes=True)

    id: int
    user_id: int
    role: str
    difficulty: str
    status: str
    total_questions: int
    current_question_index: int
    overall_score: float | None = None
    summary_feedback: str | None = None
    current_question: InterviewQuestionResponse | None = None
    questions: list[InterviewQuestionResponse] = Field(default_factory=list)
    created_at: datetime
    completed_at: datetime | None = None


class InterviewResultsResponse(BaseModel):
    """Response schema for final completed interview performance report."""

    session_id: int
    user_id: int
    role: str
    difficulty: str
    overall_score: float
    metrics_breakdown: dict[str, float] = Field(default_factory=dict)
    summary_feedback: str
    strengths: list[str] = Field(default_factory=list)
    improvements: list[str] = Field(default_factory=list)
    questions_transcript: list[InterviewQuestionResponse] = Field(default_factory=list)
    completed_at: datetime | None = None
