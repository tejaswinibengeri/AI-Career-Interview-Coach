"""
Pydantic schemas for Career Selection and Skill Gap Analysis.
"""

from datetime import datetime
from pydantic import BaseModel, ConfigDict, Field


class CareerSkillResponse(BaseModel):
    """Occupation skill requirement."""

    name: str
    category: str = "technical"
    importance: float = 80.0
    level: float = 70.0


class OccupationResponse(BaseModel):
    """Occupation details."""

    model_config = ConfigDict(from_attributes=True)

    id: int
    code: str
    title: str
    description: str
    industry: str
    skills: list[CareerSkillResponse] = Field(default_factory=list)


class SkillGapRequest(BaseModel):
    """Request payload to trigger skill gap analysis."""

    occupation_id: int = Field(..., description="Target occupation ID to analyze against")


class CareerGoalRequest(BaseModel):
    """Request payload to set active target career goal."""

    occupation_id: int = Field(..., description="Target occupation ID to set as career goal")


class AISkillGapExplanationPayload(BaseModel):
    """Schema to validate JSON explanation generated by Ollama."""

    explanation: str = Field(..., description="Detailed narrative explanation of the skill gap analysis")
    learning_order: list[dict] = Field(
        default_factory=list,
        description="List of step-by-step learning recommendations: [{'step': 1, 'skill_name': '...', 'rationale': '...'}]",
    )


class SkillGapReportResponse(BaseModel):
    """Full skill gap evaluation report response."""

    model_config = ConfigDict(from_attributes=True)

    id: int
    user_id: int
    occupation_id: int
    occupation_title: str
    match_percentage: float
    strong_skills: list[dict] = Field(default_factory=list)
    intermediate_skills: list[dict] = Field(default_factory=list)
    missing_skills: list[dict] = Field(default_factory=list)
    learning_order: list[dict] = Field(default_factory=list)
    ai_explanation: str
    created_at: datetime
